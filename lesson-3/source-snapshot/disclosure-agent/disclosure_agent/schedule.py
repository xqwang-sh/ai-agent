"""Native one-minute tick tasks; business dates always use Asia/Shanghai.

macOS launchd is the target for real-machine acceptance. Windows Task Scheduler XML is generated by
this adapter but requires a separate real-machine acceptance run.
"""
from __future__ import annotations

import hashlib
import json
import os
import platform
import plistlib
import subprocess
import sys
import uuid
from contextlib import contextmanager
from datetime import datetime, timedelta
from pathlib import Path
from xml.sax.saxutils import escape
from zoneinfo import ZoneInfo

TZ = ZoneInfo('Asia/Shanghai')


def _now():
    return datetime.now(TZ)


def _root(workspace):
    root = Path(workspace).resolve() / 'schedule'
    root.mkdir(parents=True, exist_ok=True)
    return root


def _write(path, data):
    temp = path.with_name(path.name + '.' + uuid.uuid4().hex + '.tmp')
    temp.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf-8')
    os.replace(temp, path)


@contextmanager
def _lock(workspace, name='tick.lock'):
    handle = (_root(workspace) / name).open('a+b')
    locked = False
    try:
        if os.name == 'nt':
            import msvcrt
            handle.seek(0)
            handle.write(b'0')
            handle.flush()
            handle.seek(0)
            try:
                msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
                locked = True
            except OSError:
                pass
        else:
            import fcntl
            try:
                fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
                locked = True
            except BlockingIOError:
                pass
        yield handle if locked else None
    finally:
        if locked:
            if os.name == 'nt':
                handle.seek(0)
                msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                fcntl.flock(handle.fileno(), fcntl.LOCK_UN)
        handle.close()


def _load(workspace):
    return json.loads((_root(workspace) / 'plan.json').read_text(encoding='utf-8'))


def _os_command(args):
    result = subprocess.run(args, capture_output=True, text=True, timeout=30)
    return {'returncode': result.returncode, 'stdout': result.stdout[-4000:], 'stderr': result.stderr[-2000:]}


def install(config_path: Path, workspace: Path, project_root: Path) -> dict:
    workspace, project_root, config_path = Path(workspace).resolve(), Path(project_root).resolve(), Path(config_path).resolve()
    if not config_path.is_file() or not (project_root / 'run_agent.py').is_file():
        raise ValueError('Config and run_agent.py must exist before installing a schedule')
    root = _root(workspace)
    plan_path = root / 'plan.json'
    if plan_path.exists():
        raise FileExistsError('A schedule already exists for this workspace; inspect status or resume it')
    suffix = hashlib.sha256(str(workspace).encode()).hexdigest()[:12]
    label = f'local.disclosure-agent.{suffix}'
    python = str(Path(sys.executable).absolute())
    command = [python, str(project_root / 'run_agent.py'), 'tick', '--config', str(config_path), '--workspace', str(workspace)]
    plan = {'label': label, 'platform': platform.system(), 'enabled': True,
            'installed_at': _now().isoformat(), 'config_path': str(config_path),
            'workspace': str(workspace), 'project_root': str(project_root), 'python': python,
            'timezone': 'Asia/Shanghai', 'weekdays': [0, 1, 2, 3, 4], 'time': '08:30',
            'tick_seconds': 60, 'claims': [], 'test_due': None,
            'pause_behavior': 'The OS still ticks every minute; pause blocks new business runs and lets an active run finish.',
            'wake_policy': 'Catch up the current weekday after 08:30; skip dates before install and past dates.'}
    if plan['platform'] == 'Darwin':
        plist_path = Path.home() / 'Library' / 'LaunchAgents' / f'{label}.plist'
        plist_path.parent.mkdir(parents=True, exist_ok=True)
        if plist_path.exists():
            raise FileExistsError(f'Task file already exists: {plist_path}')
        payload = {'Label': label, 'ProgramArguments': command, 'StartInterval': 60,
                   'WorkingDirectory': str(project_root), 'RunAtLoad': False,
                   'StandardOutPath': str(root / 'tick.stdout.log'), 'StandardErrorPath': str(root / 'tick.stderr.log')}
        with plist_path.open('xb') as stream:
            plistlib.dump(payload, stream)
        try:
            result = _os_command(['launchctl', 'bootstrap', f'gui/{os.getuid()}', str(plist_path)])
            if result['returncode']:
                raise RuntimeError(f"launchd registration failed: {result['stderr']}")
        except Exception:
            plist_path.unlink()
            raise
        plan.update({'task_path': str(plist_path), 'registered': True, 'platform_verified': False})
    elif plan['platform'] == 'Windows':
        import subprocess as sp
        xml_path = root / 'task.xml'
        boundary = (_now() + timedelta(minutes=1)).replace(tzinfo=None).isoformat(timespec='seconds')
        arguments = sp.list2cmdline(command[1:])
        xml = f'''<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
<Triggers><TimeTrigger><Repetition><Interval>PT1M</Interval><Duration>P1D</Duration><StopAtDurationEnd>false</StopAtDurationEnd></Repetition><StartBoundary>{boundary}</StartBoundary><Enabled>true</Enabled></TimeTrigger></Triggers>
<Principals><Principal id="Author"><LogonType>InteractiveToken</LogonType><RunLevel>LeastPrivilege</RunLevel></Principal></Principals>
<Settings><MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy><StartWhenAvailable>true</StartWhenAvailable><ExecutionTimeLimit>PT1H</ExecutionTimeLimit></Settings>
<Actions Context="Author"><Exec><Command>{escape(command[0])}</Command><Arguments>{escape(arguments)}</Arguments><WorkingDirectory>{escape(str(project_root))}</WorkingDirectory></Exec></Actions></Task>'''
        # CalendarTrigger repeats indefinitely; the tick itself decides business weekdays.
        xml = xml.replace('<TimeTrigger>', '<CalendarTrigger>').replace('</TimeTrigger>', '</CalendarTrigger>').replace('<Enabled>true</Enabled></CalendarTrigger>', '<Enabled>true</Enabled><ScheduleByDay><DaysInterval>1</DaysInterval></ScheduleByDay></CalendarTrigger>')
        xml_path.write_text(xml, encoding='utf-16')
        result = _os_command(['schtasks', '/Create', '/TN', label, '/XML', str(xml_path)])
        if result['returncode']:
            raise RuntimeError(f"Windows task registration failed: {result['stderr']}")
        plan.update({'task_path': str(xml_path), 'registered': True, 'platform_verified': False,
                     'limitation': 'Windows adapter has not been verified on a real Windows machine.'})
    else:
        raise NotImplementedError('Only macOS and Windows scheduling are implemented')
    _write(plan_path, plan)
    return status(workspace)


def status(workspace: Path) -> dict:
    try:
        plan = _load(workspace)
    except FileNotFoundError:
        return {'installed': False, 'enabled': False}
    command = (['launchctl', 'print', f"gui/{os.getuid()}/{plan['label']}"]
               if plan['platform'] == 'Darwin' else ['schtasks', '/Query', '/TN', plan['label'], '/V'])
    result = _os_command(command)
    return {**plan, 'installed': result['returncode'] == 0, 'os_task': result}


def _enabled(workspace, value):
    with _lock(workspace) as locked:
        if not locked:
            raise RuntimeError('Another schedule setting update is in progress; retry shortly')
        plan = _load(workspace)
        plan['enabled'] = value
        _write(_root(workspace) / 'plan.json', plan)
    return status(workspace)


def pause(workspace: Path) -> dict:
    """Disable future business starts; leave the minute timer and active run intact."""
    return _enabled(workspace, False)


def resume(workspace: Path) -> dict:
    return _enabled(workspace, True)


def test_after(workspace: Path, seconds: int = 90) -> dict:
    if not isinstance(seconds, int) or not 1 <= seconds <= 86400:
        raise ValueError('Test delay must be 1 to 86400 seconds')
    with _lock(workspace) as locked:
        if not locked:
            raise RuntimeError('A scheduled run is in progress')
        plan = _load(workspace)
        if not plan['enabled']:
            raise ValueError('Resume the persistent task before scheduling its test')
        if plan.get('test_due'):
            raise ValueError('A future test is already pending')
        plan['test_due'] = (_now() + timedelta(seconds=seconds)).isoformat()
        _write(_root(workspace) / 'plan.json', plan)
    return {'test_due': plan['test_due'], 'label': plan['label'], 'mode': 'real_os_tick', 'requires_os_task': True}


def _finalize(workspace, claim, record):
    """A terminal result is durable before its schedule slot is marked complete."""
    root = _root(workspace)
    result_path = Path(claim['execution_path']) / 'result.json'
    if not result_path.exists():
        _write(result_path, record)
    _write(root / 'last_execution.json', record)
    with _lock(workspace) as locked:
        if not locked:
            # The next tick observes result.json and finishes the plan update.
            return record
        plan = _load(workspace)
        if claim['id'] not in plan['claims']:
            plan['claims'].append(claim['id'])
        if plan.get('pending_claim', {}).get('id') == claim['id']:
            plan.pop('pending_claim', None)
        if claim['kind'] == 'test' and plan.get('test_due') == claim['scheduled_for']:
            plan['test_due'] = None
        _write(root / 'plan.json', plan)
    return record


def _published_run(workspace, claim):
    """Recover a finished child after its parent tick died before saving a result."""
    try:
        from .runner import load_publication
        state, summary = load_publication(Path(workspace))
        run_id = summary.get('run_id')
        if (not isinstance(run_id, str) or run_id in claim['run_ids_before']
                or summary.get('trigger') != 'scheduler'
                or summary.get('schedule_claim_id') != claim['id']
                or summary.get('status') not in {'complete', 'needs_review', 'incomplete'}
                or state.get('last_run_id') != run_id
                or not Path(summary.get('output_html', str(Path(workspace) / 'calendar.html'))).is_file()):
            return None
        run_dir = Path(workspace) / 'runs' / run_id
        archived = json.loads((run_dir / 'summary.json').read_text(encoding='utf-8'))
        if (archived.get('run_id') != run_id
                or archived.get('schedule_claim_id') != claim['id']
                or archived.get('trigger') != 'scheduler'):
            return None
        return summary
    except (OSError, ValueError, TypeError, KeyError):
        return None


def _execution_record(workspace, claim, **fields):
    execution = Path(claim['execution_path'])
    return {'status': 'running', 'execution_status': 'running', 'business_status': None,
            'trigger': 'scheduler', 'kind': claim['kind'], 'scheduled_for': claim['scheduled_for'],
            'schedule_claim_id': claim['id'],
            'actual_start': claim['actual_start'], 'label': claim['label'], 'run_id': None,
            'outputs': [str(path.resolve()) for path in Path(workspace).glob('*')
                        if path.is_file() and path.suffix in {'.json', '.html'}],
            'evidence_path': str((execution / 'result.json').resolve()), **fields}


def tick(config_path: Path, workspace: Path, project_root: Path) -> dict:
    root = _root(workspace)
    # This separate lock covers execution while plan/settings locks stay short.
    with _lock(workspace, 'execution.lock') as execution_lock:
        if not execution_lock:
            return {'status': 'skipped_overlap'}
        with _lock(workspace) as locked:
            if not locked:
                return {'status': 'skipped_overlap'}
            plan = _load(workspace)
            if str(Path(config_path).resolve()) != plan['config_path'] or str(Path(project_root).resolve()) != plan['project_root']:
                raise ValueError('Tick arguments differ from the installed project schedule')
            if not plan['enabled']:
                return {'status': 'paused'}
            now = _now()
            claim = plan.get('pending_claim')
            if claim is None:
                due, kind = None, None
                if plan.get('test_due') and now >= datetime.fromisoformat(plan['test_due']):
                    due, kind = datetime.fromisoformat(plan['test_due']), 'test'
                else:
                    hour, minute = map(int, plan['time'].split(':'))
                    business_due = now.replace(hour=hour, minute=minute, second=0, microsecond=0)
                    if now.weekday() in plan['weekdays'] and now >= business_due >= datetime.fromisoformat(plan['installed_at']):
                        due, kind = business_due, 'business'
                if due is None:
                    return {'status': 'not_due'}
                claim_id = f'{kind}:{due.isoformat()}'
                execution = root / 'executions' / hashlib.sha256(claim_id.encode()).hexdigest()[:24]
                if (execution / 'result.json').is_file():
                    terminal = json.loads((execution / 'result.json').read_text(encoding='utf-8'))
                    return {**terminal, 'status': 'already_claimed', 'terminal_status': terminal['status']}
                execution.mkdir(parents=True, exist_ok=True)
                claim_file = execution / 'claim.json'
                if claim_file.exists():
                    claim = json.loads(claim_file.read_text(encoding='utf-8'))
                else:
                    claim = {'id': claim_id, 'kind': kind, 'scheduled_for': due.isoformat(),
                             'claim_status': 'running',
                             'actual_start': now.isoformat(), 'label': plan['label'],
                             'execution_path': str(execution),
                             'run_ids_before': [path.name for path in (Path(workspace) / 'runs').glob('*')]}
                    _write(claim_file, claim)
                # A pending claim remains recoverable; claims/test_due mark completion only.
                plan['pending_claim'] = claim
                _write(root / 'plan.json', plan)
        result_path = Path(claim['execution_path']) / 'result.json'
        if result_path.exists():
            record = json.loads(result_path.read_text(encoding='utf-8'))
            return _finalize(workspace, claim, {**record, 'recovered': True})
        published = _published_run(workspace, claim)
        if published:
            record = _execution_record(workspace, claim, status='complete', execution_status='complete',
                        business_status=published['status'], run_id=published['run_id'],
                        run_dir=str((Path(workspace) / 'runs' / published['run_id']).resolve()),
                        exit_code=None, actual_end=published.get('finished_at', _now().isoformat()),
                        recovered=True)
            return _finalize(workspace, claim, record)
        attempt = Path(claim['execution_path']) / ('attempt-' + uuid.uuid4().hex[:12])
        attempt.mkdir()
        record = _execution_record(workspace, claim, actual_start=_now().isoformat(), attempt_path=str(attempt))
        _write(attempt / 'claim.json', record)
        command = [plan['python'], str(Path(project_root).resolve() / 'run_agent.py'), 'run', '--config', plan['config_path'],
                   '--workspace', str(Path(workspace).resolve()), '--trigger', 'scheduler', '--claim-id', claim['id']]
        before = set((Path(workspace) / 'runs').glob('*'))
        try:
            kwargs = {'cwd': plan['project_root'], 'capture_output': True, 'text': True, 'timeout': 1800}
            if os.name != 'nt':
                # A surviving child keeps execution locked if its parent tick is killed.
                kwargs['pass_fds'] = (execution_lock.fileno(),)
            result = subprocess.run(command, **kwargs)
            record.update({'exit_code': result.returncode,
                           'status': 'complete' if result.returncode == 0 else 'failed',
                           'execution_status': 'complete' if result.returncode == 0 else 'failed'})
            try:
                parsed = json.loads(result.stdout)
            except (ValueError, TypeError):
                parsed = {}
            if isinstance(parsed, dict):
                record['run_id'] = parsed.get('run_id')
                record['business_status'] = parsed.get('status')
                if record['run_id'] and record['business_status'] in {'complete', 'needs_review', 'incomplete'}:
                    record.update({'status': 'complete', 'execution_status': 'complete'})
                elif record['business_status'] == 'skipped_overlap':
                    record.update({'status': 'skipped_overlap', 'execution_status': 'not_started'})
        except Exception as exc:
            record.update({'status': 'failed', 'execution_status': 'failed', 'exit_code': None,
                           'error': f'{type(exc).__name__}: scheduled command failed'})
        new_runs = sorted(set((Path(workspace) / 'runs').glob('*')) - before)
        if record['run_id'] is None:
            for run_dir in new_runs:
                try:
                    started = json.loads((run_dir / 'start.json').read_text(encoding='utf-8'))
                except (OSError, ValueError):
                    continue
                if started.get('schedule_claim_id') == claim['id'] and started.get('trigger') == 'scheduler':
                    record['run_id'] = run_dir.name
                    break
        if record['run_id'] is not None:
            own_run = Path(workspace) / 'runs' / record['run_id']
            if own_run.is_dir():
                record['run_dir'] = str(own_run.resolve())
        record['actual_end'] = _now().isoformat()
        record['outputs'] = [str(path.resolve()) for path in Path(workspace).glob('*')
                             if path.is_file() and path.suffix in {'.json', '.html'}]
        _write(attempt / 'result.json', record)
        if record['execution_status'] == 'not_started':
            # Another runner owns the workspace; retry this pending slot next tick.
            return record
        return _finalize(workspace, claim, record)
